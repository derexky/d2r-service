"""
Generate d2r-fe/src/pages/magic/rareNameData.ts from d2data rareprefix/raresuffix:
rare item names and the item types each can appear on (names carry no stats).
Chinese names are the official zh-TW strings, prefixes without the trailing 之.

Usage: python3 scripts/gen_rare_names.py
"""
import json

from join_affix_values import GID_TYPE

D2DATA = 'data/d2data/'
OUT = '../d2r-fe/src/pages/magic/rareNameData.ts'
RARE_GIDS = [g for g in GID_TYPE if not g.endswith('charms')]  # rare charms do not exist
# itemtypes.txt codes used by rare names -> label shown on the page
TYPE_LABELS = {
    'armo': '防具', 'weap': '武器', 'misc': '戒指/護身符/珠寶', 'tors': '護甲', 'helm': '頭盔', 'shld': '盾牌',
    'boot': '鞋子', 'glov': '手套', 'belt': '腰帶', 'ring': '戒指', 'amul': '護身符', 'jewl': '珠寶',
    'swor': '刀劍', 'knif': '匕首', 'axe': '斧', 'spea': '長矛', 'pole': '長柄武器', 'club': '短棒',
    'mace': '釘鎚', 'hamm': '重槌', 'scep': '權杖', 'blun': '鈍器', 'rod': '法杖類', 'staf': '法杖',
    'wand': '魔杖', 'orb': '法珠', 'h2h': '拳刃', 'miss': '遠程武器', 'bow': '弓', 'jave': '標槍',
}


def main():
    eng = json.load(open(D2DATA + 'localestrings-eng.json'))
    chi = json.load(open(D2DATA + 'localestrings-chi.json'))
    types = {t['Code']: t for t in json.load(open(D2DATA + 'itemtypes.json')).values() if t.get('Code')}

    def ancestors(code, out):
        if code in types and code not in out:
            out.add(code)
            for k in ('Equiv1', 'Equiv2'):
                ancestors(types[code].get(k), out)
        return out

    gid_ancestors = {g: ancestors(GID_TYPE[g], set()) for g in RARE_GIDS}

    def rows(file, prefix):
        out = {}  # by English name: the game lists some names twice (Storm), merge their item types
        for x in json.load(open(D2DATA + file)).values():
            en = eng.get(x['name'], x['name'])
            zh = chi[x['name']].removesuffix('之') if prefix else chi[x['name']]
            itypes = [x[f'itype{i}'] for i in range(1, 8) if x.get(f'itype{i}')]
            row = out.setdefault(en, {'en': en, 'zh': zh, 'types': [], 'itypes': set()})
            row['types'] += [TYPE_LABELS[t] for t in itypes if TYPE_LABELS[t] not in row['types']]
            row['itypes'] |= set(itypes)
        for row in out.values():
            itypes = row.pop('itypes')
            row['gids'] = [g for g in RARE_GIDS if gid_ancestors[g] & itypes]
        return list(out.values())

    prefixes, suffixes = rows('rareprefix.json', True), rows('raresuffix.json', False)
    fmt = lambda rs: ',\n'.join('  ' + json.dumps(r, ensure_ascii=False) for r in rs)
    open(OUT, 'w').write(
        '// Generated by d2r-service/scripts/gen_rare_names.py from game data (rareprefix/raresuffix).\n'
        '// `types`: item types the name can appear on; `gids`: the same expanded to affix page categories.\n'
        'export interface RareName { en: string; zh: string; types: string[]; gids: string[]; }\n\n'
        f'export const RARE_PREFIXES: RareName[] = [\n{fmt(prefixes)},\n];\n\n'
        f'export const RARE_SUFFIXES: RareName[] = [\n{fmt(suffixes)},\n];\n')
    print(len(prefixes), 'prefixes,', len(suffixes), 'suffixes ->', OUT)


if __name__ == '__main__':
    main()
